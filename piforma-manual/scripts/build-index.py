"""Build the back-of-book index from the compiled proof.

Each term in assets/index-terms.json is searched on the body pages of the PDF
(Chapter 1 through Appendix B, plus the credits and notices; not the contents,
glossary or index). The printed page numbers go into chapters/08-index.typ.
The index comes after every page it lists, so a second compile cannot move them.
"""
from pathlib import Path
import json,re,sys
import pymupdf as pdf
P=Path(__file__).resolve().parents[1]
OUT=P/'chapters/08-index.typ'
def page_text(page):
    # Leave out the running foot; join words split across lines.
    t=' '.join(b[4] for b in page.get_text('blocks') if b[1]<475)
    t=re.sub(r'\s+',' ',t)
    return re.sub(r'(\w)- (\w)',r'\1-\2',t)
def body_pages(doc):
    pages=[];first=None;skip=False
    for i,page in enumerate(doc):
        text=page_text(page).strip()
        label=page.get_label().replace('ageLabel','')
        if first is None and text.startswith('C H A P T E R'):first=i
        if first is None or not label.isdigit():continue
        if text.startswith('Glossary '):skip=True
        if text.startswith('Credits and acknowledgments'):skip=False
        if text.startswith('Index '):break
        # Chapter openers only preview the chapter, so they are not indexed.
        if not skip and text and not text.startswith('C H A P T E R'):pages.append((int(label),text))
    return pages
def find(patterns,pages):
    rx=[re.compile(p,re.I) for p in patterns]
    return sorted({n for n,t in pages if any(r.search(t) for r in rx)})
def ranges(nums):
    out=[];start=prev=None
    for n in nums+[None]:
        if start is not None and n==prev+1:prev=n;continue
        if start is not None:out.append(str(start) if start==prev else f'{start}–{prev}')
        start=prev=n
    return ', '.join(out)
def key(s):return re.sub(r'[^0-9a-z ]','',s.lower())
def q(s):return json.dumps(s,ensure_ascii=False)
def build(pdf_path,report=None):
    doc=pdf.open(pdf_path);pages=body_pages(doc)
    terms=json.loads((P/'assets/index-terms.json').read_text(encoding='utf-8'))['entries']
    lines=['// Generated by scripts/build-index.py from assets/index-terms.json; edit those and rebuild.',
           '#import "../styles/book.typ": *','#index-body[']
    letter=None;found={}
    for e in sorted(terms,key=lambda e:key(e['t'])):
        first=key(e['t'])[0].upper()
        if first!=letter:letter=first;lines.append(f'#index-letter({q(letter)})')
        if 'see' in e:lines.append(f'#index-see({q(e["t"])},{q(e["see"])})');continue
        nums=find(e.get('p',[]),pages);found[e['t']]=nums
        subs=[]
        for s in sorted(e.get('s',[]),key=lambda s:key(s['t'])):
            sn=find(s['p'],pages);found[e['t']+', '+s['t']]=sn
            if sn:subs.append(f'#index-sub({q(s["t"])},{q(ranges(sn))})')
        if not nums and not subs:raise SystemExit('Index term has no pages: '+e['t'])
        lines.append(f'#index-entry({q(e["t"])},{q(ranges(nums))})');lines+=subs
    lines.append(']')
    text='\n'.join(lines)+'\n'
    if report:Path(report).write_text(json.dumps(found,indent=1,ensure_ascii=False),encoding='utf-8')
    changed=not OUT.exists() or OUT.read_text(encoding='utf-8')!=text
    OUT.write_text(text,encoding='utf-8')
    return changed
if __name__=='__main__':
    print('changed' if build(sys.argv[1] if len(sys.argv)>1 else P/'output/macintosh-piforma-working-proof.pdf',sys.argv[2] if len(sys.argv)>2 else None) else 'unchanged')
